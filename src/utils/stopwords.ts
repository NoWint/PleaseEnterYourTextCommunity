// 内置中文停用词表: 口水词/助词/语气词/常见口语, 词频统计时过滤。
// 加标点/数字/单字正则, 避免「的了是」「啊」等污染主题关键词。

// 常见停用词: 助词、代词、语气词、高频口语。分词后若命中 → 丢弃。
export const STOPWORDS: ReadonlySet<string> = new Set([
  // 助词/虚词
  '的', '了', '是', '在', '我', '有', '和', '就', '都', '而', '及', '与', '着', '或', '一个',
  '没有', '我们', '你们', '他们', '她们', '它', '这', '那', '这个', '那个', '这些', '那些',
  '什么', '怎么', '为什么', '哪里', '哪儿', '谁', '哪个', '多少',
  '不', '没', '很', '太', '也', '还', '又', '再', '才', '只', '但是', '可是', '不过',
  '因为', '所以', '如果', '虽然', '然后', '而且', '并且', '或者', '但是', '于是',
  '可以', '应该', '需要', '必须', '觉得', '知道', '认为', '希望', '可能', '一般',
  // 语气词/口语
  '啊', '嗯', '哦', '吧', '呢', '了', '吗', '呀', '哈', '嘿', '唉', '呃',
  '哈哈', '呵呵', '嘿嘿', '嗯嗯', '哦哦', '好', '好的', '行', '行吧', '可以',
  '就是', '反正', '真的', '其实', '感觉', '好像', '这样', '那样', '时候', '东西',
  '已经', '现在', '今天', '明天', '昨天', '大家', '朋友', '我们',
]);

// 标点/符号/空白/数字, 命中 → 丢弃
export const FILTER_RE = /^[0-9a-zA-Z\s，。！？、；：“”‘’（）【】《》〈〉「」『』…—·.,;:!?'"()\[\]{}<>\/\\|_+=\-*&^%$#@`~]+$/;

// 单字过滤: 长度 < 2 的中文单字词信息量低(「的」「是」已在停用词, 其余如「做」「看」无主题意义), 丢弃。
export const MIN_WORD_LEN = 2;

/** 判断单个词是否应被过滤。 */
export function isStopword(word: string): boolean {
  if (word.length < MIN_WORD_LEN) return true;
  if (STOPWORDS.has(word)) return true;
  if (FILTER_RE.test(word)) return true;
  return false;
}
